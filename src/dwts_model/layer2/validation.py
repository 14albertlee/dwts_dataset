"""Validation of the random-fan null model: simulate the rule independently and compare with the forecast.

If fan rankings really were uniformly random, eliminations are generated by drawing a random permutation
and applying the week's scalar rule (`rules.eliminated_index*`) one draw at a time, after the forecast's
own uniform mixing (eps). That path shares no code with the forecaster (`Rule.elimination_terms`:
enumeration / vectorised draws), so agreement between the observed metrics in simulated worlds and the
expected metrics implied by the forecast checks both.
"""
import numpy as np
import pandas as pd

from .metrics import P_MIN
from .rules import eliminated_index, eliminated_index_save, judge_points


def _simulate_week(scores, era: str, tie: str, eps: float, save_q: float, rng) -> int:
    n = len(scores)
    if rng.random() < eps:
        return int(rng.integers(n))
    fans = rng.permutation(n) + 1
    jp = judge_points(scores, tie)
    if era == "save":
        return eliminated_index_save(scores, jp, fans, save_q, rng)
    return eliminated_index(jp, fans)


def simulate_null_eliminations(cw: pd.DataFrame, weeks: pd.DataFrame, tie: str, rng: np.random.Generator) -> dict:
    """{(season, week): index of the eliminated couple} for one simulated world, uniform random fan rankings.

    `weeks` has season, week and optionally era, eps, save_q (defaults: rank rule, no mixing).
    """
    index = cw.groupby(["season", "week"]).indices
    out = {}
    for row in weeks.itertuples(index=False):
        scores = cw.iloc[index[(row.season, row.week)]]["score"].to_numpy()
        out[(row.season, row.week)] = _simulate_week(
            scores, getattr(row, "era", "rank"), tie, getattr(row, "eps", 0.0), getattr(row, "save_q", 1.0), rng,
        )
    return out


def _outcome_metrics(p: np.ndarray, e: int) -> dict:
    above, tied = int((p > p[e]).sum()), int((p == p[e]).sum())
    return {
        "top1": float(np.clip((1 - above) / tied, 0, 1)),
        "logloss": -np.log(max(p[e], P_MIN)),
        "brier": float(((p - (np.arange(len(p)) == e)) ** 2).sum()),
        "p_actual": p[e],
    }


def expected_week_metrics(p: np.ndarray) -> dict:
    """Metrics averaged over which couple is eliminated, if the elimination follows p."""
    rows = [_outcome_metrics(p, e) for e in range(len(p))]
    return {k: float(sum(p[e] * rows[e][k] for e in range(len(p)))) for k in rows[0]}


def null_self_consistency(probs: pd.DataFrame, cw: pd.DataFrame, tie: str, n_rep: int = 30, seed: int = 0) -> pd.DataFrame:
    """Compare expected and simulated-world metrics for null-model `probs` (one row per couple-week).

    Each metric is the mean over weeks; `se` is the standard error across simulated worlds.
    """
    rng = np.random.default_rng(seed)
    week_cols = [c for c in ("season", "week", "era", "eps", "save_q") if c in probs.columns]
    weeks = probs[week_cols].drop_duplicates(["season", "week"])
    groups = probs.groupby(["season", "week"]).indices
    p_by_week = {k: probs.iloc[v]["p_elim"].to_numpy() for k, v in groups.items()}
    expected = pd.DataFrame([expected_week_metrics(p_by_week[(s, w)]) for s, w in zip(weeks["season"], weeks["week"])])

    observed = []
    for _ in range(n_rep):
        eliminated = simulate_null_eliminations(cw, weeks, tie, rng)
        observed.append(pd.DataFrame([_outcome_metrics(p_by_week[k], e) for k, e in eliminated.items()]).mean())
    observed = pd.DataFrame(observed)
    out = pd.DataFrame(
        {"expected": expected.mean(), "observed": observed.mean(), "se": observed.std(ddof=1) / np.sqrt(n_rep)}
    )
    out["z"] = (out["observed"] - out["expected"]) / out["se"]
    return out.reset_index(names="metric")
